import { useRef, useEffect, useState } from 'react'
import { askFinanceAgent } from '../api/chat'
import Badge from './Badge'

interface Message {
  role: 'user' | 'assistant' | 'error'
  text: string
  toolsUsed?: string[]
}

const EXAMPLES = [
  'Why did my spending increase this month?',
  'How much did I spend on food last month?',
  'Am I over budget on anything?',
  'Compare my August and September spending',
  'What will next month look like?',
]

export default function FinanceChat() {
  const [messages, setMessages] = useState<Message[]>([])
  const [input, setInput] = useState('')
  const [loading, setLoading] = useState(false)
  const bottomRef = useRef<HTMLDivElement>(null)

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: 'smooth' })
  }, [messages, loading])

  const send = async (text: string) => {
    const question = text.trim()
    if (!question || loading) return
    setInput('')
    setMessages((m) => [...m, { role: 'user', text: question }])
    setLoading(true)
    try {
      const res = await askFinanceAgent(question)
      setMessages((m) => [...m, { role: 'assistant', text: res.answer, toolsUsed: res.tools_used }])
    } catch (err) {
      setMessages((m) => [...m, { role: 'error', text: err instanceof Error ? err.message : 'Something went wrong' }])
    } finally {
      setLoading(false)
    }
  }

  return (
    <div className="max-w-3xl mx-auto p-6">
      <h1 className="text-2xl font-semibold text-slate-800">Ask FinSight</h1>
      <p className="text-slate-500 text-sm mb-4">
        Answers are generated by an AI agent that looks up your real data using tools. It never estimates numbers itself.
      </p>

      <div className="bg-white rounded-lg shadow-sm border border-slate-100 p-4 min-h-[320px] max-h-[520px] overflow-y-auto space-y-3">
        {messages.length === 0 && (
          <div>
            <p className="text-slate-400 text-sm mb-3">Try asking:</p>
            <div className="flex flex-wrap gap-2">
              {EXAMPLES.map((q) => (
                <button
                  key={q}
                  onClick={() => send(q)}
                  className="text-xs border border-slate-200 rounded-full px-3 py-1.5 text-slate-600 hover:bg-slate-50"
                >
                  {q}
                </button>
              ))}
            </div>
          </div>
        )}

        {messages.map((m, i) => (
          <div key={i} className={m.role === 'user' ? 'flex justify-end' : 'flex justify-start'}>
            <div
              className={`max-w-[85%] rounded-lg px-3 py-2 text-sm whitespace-pre-wrap ${
                m.role === 'user'
                  ? 'bg-slate-800 text-white'
                  : m.role === 'error'
                    ? 'bg-red-50 text-red-600'
                    : 'bg-slate-50 text-slate-800 border border-slate-100'
              }`}
            >
              {m.text}
              {m.role === 'assistant' && (
                <div className="mt-2 pt-2 border-t border-slate-200 flex flex-wrap items-center gap-1.5">
                  <Badge kind="ai" small />
                  {m.toolsUsed && m.toolsUsed.length > 0 ? (
                    <span className="text-[10px] text-slate-400">
                      Data from: {[...new Set(m.toolsUsed)].join(', ')}
                    </span>
                  ) : (
                    <span className="text-[10px] text-slate-400">No data tools used</span>
                  )}
                </div>
              )}
            </div>
          </div>
        ))}

        {loading && <p className="text-slate-400 text-sm">Looking that up...</p>}
        <div ref={bottomRef} />
      </div>

      <div className="flex gap-2 mt-3">
        <input
          value={input}
          onChange={(e) => setInput(e.target.value)}
          onKeyDown={(e) => e.key === 'Enter' && send(input)}
          placeholder="Ask anything about your finances..."
          className="flex-1 border border-slate-200 rounded-lg px-3 py-2 text-sm"
        />
        <button
          onClick={() => send(input)}
          disabled={loading || !input.trim()}
          className="bg-slate-800 text-white px-4 py-2 rounded-lg text-sm hover:bg-slate-700 disabled:opacity-40"
        >
          Send
        </button>
      </div>
    </div>
  )
}
